using System.Diagnostics.CodeAnalysis;
using System.Text.Json.Serialization;

namespace Kazo.Os.AppSdk;

/// <summary>
/// Names the <see cref="JsonSerializerContext"/> of an app assembly whose types may cross a process
/// boundary (ADR 0124, section 2): the payload of a topic message or a typed event received or
/// published by a process running in a Web Worker, and the data of a background task (ADR 0128).
/// </summary>
/// <remarks>
/// <para>
/// A process in a worker runs in a separate .NET runtime: an object of its heap cannot be handed to
/// the OS's heap, so it travels as JSON, like data written to a pipe. The context must be generated by
/// System.Text.Json (<c>[JsonSerializable(typeof(MyEvent))]</c> on a <c>partial</c> class deriving
/// <see cref="JsonSerializerContext"/>), so it keeps working in a trimmed publish (ADR 0113).
/// </para>
/// <para>
/// On the main thread nothing changes: objects are passed by reference and this attribute is not
/// read. In a worker, a payload whose type is neither an event type of the OS nor covered by a
/// declared context fails with a <see cref="NotSupportedException"/> that names the type and this
/// attribute.
/// </para>
/// <example>
/// <code>
/// [assembly: HackWireContext(typeof(TickerJsonContext))]
///
/// [JsonSerializable(typeof(TickerEvent))]
/// internal sealed partial class TickerJsonContext : JsonSerializerContext;
/// </code>
/// </example>
/// </remarks>
[AttributeUsage(AttributeTargets.Assembly, AllowMultiple = true)]
public sealed class HackWireContextAttribute : Attribute
{
    /// <summary>Initializes the attribute.</summary>
    /// <param name="contextType">
    /// A non-abstract class deriving <see cref="JsonSerializerContext"/> with a public parameterless
    /// constructor (what the System.Text.Json source generator writes).
    /// </param>
    /// <exception cref="ArgumentNullException"><paramref name="contextType"/> is <see langword="null"/>.</exception>
    public HackWireContextAttribute(
        [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicParameterlessConstructor)] Type contextType)
    {
        ContextType = contextType ?? throw new ArgumentNullException(nameof(contextType));
    }

    /// <summary>Gets the type of the generated serializer context.</summary>
    [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicParameterlessConstructor)]
    public Type ContextType { get; }
}
