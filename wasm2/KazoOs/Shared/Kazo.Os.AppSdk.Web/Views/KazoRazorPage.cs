using System.Diagnostics.CodeAnalysis;
using System.Reflection;
using Kazo.Os.AppSdk.Web.Http;
using Kazo.Os.AppSdk.Web.Mvc;
using Microsoft.Extensions.DependencyInjection;

namespace Kazo.Os.AppSdk.Web.Views;

/// <summary>
/// Base of the <c>.cshtml</c> views, layouts and view starts of an ASP.Hack site (ADR 0086 §3), ASP.NET's
/// <c>RazorPage</c>. The Razor compiler of the SDK turns each <c>.cshtml</c> into a class deriving from
/// it (the site's root <c>_ViewImports.cshtml</c>, added by the build, says
/// <c>@inherits KazoRazorPage&lt;TModel&gt;</c>); its generated <see cref="ExecuteAsync"/> calls the
/// writing methods below. The view engine creates the page, sets its <c>@inject</c> properties and runs it.
/// </summary>
/// <remarks>
/// The members that the generated code calls (<see cref="WriteLiteral(string?)"/>, <see cref="Write(object?)"/>,
/// <see cref="BeginWriteAttribute"/>, <see cref="DefineSection"/>, <see cref="PushWriter"/>...) keep
/// ASP.NET's names and signatures: the compiler emits them by name.
/// </remarks>
public abstract class KazoRazorPage
{
    /// <summary>Full name of the attribute the compiler puts on <c>@inject</c> properties (declared by the site's compatibility file).</summary>
    internal const string RazorInjectAttributeName = "Microsoft.AspNetCore.Mvc.Razor.Internal.RazorInjectAttribute";

    private readonly Stack<TextWriter> _writers = new();
    private readonly List<KeyValuePair<string, Func<Task>>> _sections = [];
    private KazoViewContext? _viewContext;
    private AttributeState? _attribute;
    private string? _body;
    private bool _bodyRendered;
    private bool _bodyIgnored;

    /// <summary>Gets the context of the page: request, action, model state, view data, sections.</summary>
    public KazoViewContext ViewContext
    {
        get => _viewContext ?? throw new InvalidOperationException(
            $"{GetType().Name} is an ASP.Hack .cshtml page: it is rendered by View() or PartialView(), which give it its KazoViewContext.");
        internal set => _viewContext = value;
    }

    /// <summary>Gets the path of the page (<c>/Views/Home/Index.cshtml</c>), for error messages.</summary>
    public string Path { get; internal set; } = string.Empty;

    /// <summary>Gets the writer the page writes to (a template or a section pushes another one).</summary>
    public TextWriter Output => _writers.Count > 0 ? _writers.Peek() : throw new InvalidOperationException("The page is not being rendered.");

    /// <summary>
    /// Gets or sets the layout applied after the page, as a view name (<c>"_Layout"</c>, searched in the
    /// controller's folder then <c>Shared/</c>) or a path (<c>"~/Views/Shared/_Layout.cshtml"</c>);
    /// <see langword="null"/> means none. A view's initial value comes from its <c>_ViewStart.cshtml</c> files.
    /// </summary>
    public string? Layout { get; set; }

    /// <summary>Gets the view data shared with the controller, the partials and the layouts.</summary>
    public KazoViewDataDictionary ViewData => ViewContext.ViewData;

    /// <summary>Gets the request (ASP.NET's <c>Context</c> in a view).</summary>
    public KazoHttpContext Context => ViewContext.HttpContext;

    /// <summary>Gets the HTTP request.</summary>
    public KazoHttpRequest Request => ViewContext.HttpContext.Request;

    /// <summary>Gets the binding and validation state of the action.</summary>
    public KazoModelStateDictionary ModelState => ViewContext.ModelState;

    /// <summary>Gets whether this page is rendered as a layout (it has a body to write).</summary>
    protected bool IsLayout => _body is not null;

    /// <summary>The page's code, generated by the Razor compiler from the <c>.cshtml</c>.</summary>
    /// <returns>A task completed when the page has written its content.</returns>
    public abstract Task ExecuteAsync();

    // ------------------------------------------------------------------------------------------
    // Writing (called by the generated code)
    // ------------------------------------------------------------------------------------------

    /// <summary>Writes markup of the <c>.cshtml</c> as is.</summary>
    /// <param name="value">The markup.</param>
    public virtual void WriteLiteral(string? value)
    {
        if (!string.IsNullOrEmpty(value))
        {
            Output.Write(value);
        }
    }

    /// <summary>Writes a value as is.</summary>
    /// <param name="value">The value.</param>
    public virtual void WriteLiteral(object? value)
    {
        if (value is not null)
        {
            Output.Write(value.ToString());
        }
    }

    /// <summary>Writes an expression (<c>@Model.Title</c>): HTML-encoded, unless it is <see cref="IHackHtmlContent"/> (<c>Html.Raw</c>).</summary>
    /// <param name="value">The value; <see langword="null"/> writes nothing.</param>
    public virtual void Write(object? value) => KazoHtml.Write(Output, value);

    /// <summary>Writes a string, HTML-encoded.</summary>
    /// <param name="value">The value.</param>
    public virtual void Write(string? value) => Output.Write(KazoHtml.Encode(value));

    /// <summary>Starts an attribute whose value contains code (<c>class="note @extra"</c>), as the compiler splits it.</summary>
    /// <param name="name">Attribute name.</param>
    /// <param name="prefix">Text before the value (<c> class="</c>).</param>
    /// <param name="prefixOffset">Position in the source (unused).</param>
    /// <param name="suffix">Text after the value (<c>"</c>).</param>
    /// <param name="suffixOffset">Position in the source (unused).</param>
    /// <param name="attributeValuesCount">Number of value parts; with one part, a <see langword="null"/> or <see langword="false"/> value removes the attribute.</param>
    public virtual void BeginWriteAttribute(string name, string prefix, int prefixOffset, string suffix, int suffixOffset, int attributeValuesCount)
    {
        ArgumentNullException.ThrowIfNull(prefix);
        ArgumentNullException.ThrowIfNull(suffix);
        _attribute = new AttributeState(name, prefix, suffix, attributeValuesCount);

        // With one value the prefix waits: the value decides whether the attribute is written at all.
        if (attributeValuesCount != 1)
        {
            WriteLiteral(prefix);
        }
    }

    /// <summary>Writes one part of an attribute value (ASP.NET's rules: see <see cref="BeginWriteAttribute"/>).</summary>
    /// <param name="prefix">Whitespace before the part.</param>
    /// <param name="prefixOffset">Position in the source (unused).</param>
    /// <param name="value">The part.</param>
    /// <param name="valueOffset">Position in the source (unused).</param>
    /// <param name="valueLength">Length in the source (unused).</param>
    /// <param name="isLiteral">Whether the part is literal markup (not encoded) rather than code.</param>
    public virtual void WriteAttributeValue(string prefix, int prefixOffset, object? value, int valueOffset, int valueLength, bool isLiteral)
    {
        AttributeState attribute = _attribute ?? throw new InvalidOperationException("WriteAttributeValue was called outside of an attribute.");
        if (attribute.ValueCount == 1)
        {
            if (string.IsNullOrEmpty(prefix) && (value is null || value is false))
            {
                // checked="@false" or title="@null": no attribute at all, as in ASP.NET.
                attribute.Suppressed = true;
                return;
            }

            WriteLiteral(attribute.Prefix);
            if (string.IsNullOrEmpty(prefix) && value is true)
            {
                // checked="@true" writes checked="checked".
                value = attribute.Name;
            }
        }

        if (value is null)
        {
            return;
        }

        if (!string.IsNullOrEmpty(prefix))
        {
            WriteLiteral(prefix);
        }

        if (isLiteral)
        {
            WriteLiteral(value);
        }
        else
        {
            Write(value);
        }
    }

    /// <summary>Ends the attribute started by <see cref="BeginWriteAttribute"/>.</summary>
    public virtual void EndWriteAttribute()
    {
        AttributeState attribute = _attribute ?? throw new InvalidOperationException("EndWriteAttribute was called outside of an attribute.");
        _attribute = null;
        if (!attribute.Suppressed)
        {
            WriteLiteral(attribute.Suffix);
        }
    }

    /// <summary>Redirects the output (an inline template writes into its own writer).</summary>
    /// <param name="writer">The writer.</param>
    public void PushWriter(TextWriter writer)
    {
        ArgumentNullException.ThrowIfNull(writer);
        _writers.Push(writer);
    }

    /// <summary>Restores the output redirected by <see cref="PushWriter"/>.</summary>
    /// <returns>The writer that was in use.</returns>
    public TextWriter PopWriter() => _writers.Pop();

    // ------------------------------------------------------------------------------------------
    // Sections and body
    // ------------------------------------------------------------------------------------------

    /// <summary>Defines a section (<c>@section Scripts { ... }</c>), which the layout writes with <see cref="RenderSection(string, bool)"/>.</summary>
    /// <param name="name">The section name.</param>
    /// <param name="section">Writes the section's content.</param>
    /// <exception cref="InvalidOperationException">The page already defines this section.</exception>
    public virtual void DefineSection(string name, Func<Task> section)
    {
        ArgumentException.ThrowIfNullOrEmpty(name);
        ArgumentNullException.ThrowIfNull(section);
        if (_sections.Any(pair => string.Equals(pair.Key, name, StringComparison.OrdinalIgnoreCase)))
        {
            throw new InvalidOperationException($"Section '{name}' is already defined.");
        }

        _sections.Add(KeyValuePair.Create(name, section));
    }

    /// <summary>In a layout, writes the HTML of the view (or of the inner layout).</summary>
    /// <returns>The body.</returns>
    /// <exception cref="InvalidOperationException">The page is not a layout.</exception>
    public KazoHtmlString RenderBody()
    {
        string body = _body ?? throw new InvalidOperationException($"RenderBody invocation in '{Path}' is invalid. RenderBody can only be called from a layout page.");
        _bodyRendered = true;
        return new KazoHtmlString(body);
    }

    /// <summary>In a layout, accepts not writing the body.</summary>
    public void IgnoreBody() => _bodyIgnored = true;

    /// <summary>In a layout, writes a section the view defined; a missing section is an error.</summary>
    /// <param name="name">The section name.</param>
    /// <returns>The section.</returns>
    public KazoHtmlString? RenderSection(string name) => RenderSection(name, required: true);

    /// <summary>In a layout, writes a section the view defined.</summary>
    /// <param name="name">The section name.</param>
    /// <param name="required">Whether a view without this section is an error.</param>
    /// <returns>The section, or <see langword="null"/> (nothing written) when it is not defined and not required.</returns>
    /// <exception cref="InvalidOperationException">The page is not a layout, or a required section is missing.</exception>
    public KazoHtmlString? RenderSection(string name, bool required)
    {
        ArgumentException.ThrowIfNullOrEmpty(name);
        EnsureLayout(nameof(RenderSection));
        if (ViewContext.TryRenderSectionHtml(name, out string? html))
        {
            return new KazoHtmlString(html);
        }

        return required
            ? throw new InvalidOperationException($"The layout page '{Path}' cannot find the section '{name}' in the content page.")
            : null;
    }

    /// <summary>Same as <see cref="RenderSection(string)"/>, for <c>@await RenderSectionAsync("Scripts")</c>.</summary>
    /// <param name="name">The section name.</param>
    public Task<KazoHtmlString?> RenderSectionAsync(string name) => Task.FromResult(RenderSection(name));

    /// <summary>Same as <see cref="RenderSection(string, bool)"/>, for <c>@await RenderSectionAsync("Scripts", required: false)</c>.</summary>
    /// <param name="name">The section name.</param>
    /// <param name="required">Whether a view without this section is an error.</param>
    public Task<KazoHtmlString?> RenderSectionAsync(string name, bool required) => Task.FromResult(RenderSection(name, required));

    /// <summary>In a layout, tells whether the view defined a section.</summary>
    /// <param name="name">The section name.</param>
    public bool IsSectionDefined(string name)
    {
        ArgumentException.ThrowIfNullOrEmpty(name);
        EnsureLayout(nameof(IsSectionDefined));
        return ViewContext.IsSectionDefined(name);
    }

    /// <summary>In a layout, accepts not writing a section the view defined.</summary>
    /// <param name="name">The section name.</param>
    public void IgnoreSection(string name)
    {
        ArgumentException.ThrowIfNullOrEmpty(name);
        EnsureLayout(nameof(IgnoreSection));
        ViewContext.IgnoreSection(name);
    }

    // ------------------------------------------------------------------------------------------
    // Engine
    // ------------------------------------------------------------------------------------------

    /// <summary>Sets the model (typed by <see cref="KazoRazorPage{TModel}"/>).</summary>
    /// <param name="model">The model, already checked by the engine.</param>
    private protected abstract void SetModel(object? model);

    /// <summary>
    /// Gets the value of an <c>@inject</c> property that is a helper of this page (<c>Html</c>, <c>Json</c>,
    /// <c>Component</c>, <c>Url</c>, <c>ModelExpressionProvider</c>), or <see langword="null"/> for a service.
    /// </summary>
    /// <param name="type">The property type.</param>
    private protected virtual object? CreateHelper(Type type) =>
        type == typeof(IHackUrlHelper) ? ViewContext.Url
        : type == typeof(KazoJsonHelper) ? new KazoJsonHelper(this)
        : type == typeof(KazoViewComponentHelper) ? new KazoViewComponentHelper(this)
        : null;

    /// <summary>
    /// Runs the page and returns its HTML (ADR 0086 §5): context and model set, <c>@inject</c> properties
    /// filled, <see cref="ExecuteAsync"/> run, body checked, then its sections rendered to HTML into the
    /// page context, where the layout finds them.
    /// </summary>
    /// <param name="pageType">The page class (its <c>@inject</c> properties are read from it).</param>
    /// <param name="viewContext">The page context.</param>
    /// <param name="model">The model.</param>
    /// <param name="body">The HTML of what the page wraps, for a layout; <see langword="null"/> for a view.</param>
    /// <param name="layout">The initial <see cref="Layout"/> (from the view starts).</param>
    internal Task<string> RenderAsync(
        [DynamicallyAccessedMembers(KazoViewTypes.Component)] Type pageType,
        KazoViewContext viewContext,
        object? model,
        string? body,
        string? layout)
    {
        ViewContext = viewContext;
        SetModel(model);
        _body = body;
        Layout = layout;
        Activate(pageType, viewContext.HttpContext.RequestServices);

        // The annotated pageType stays out of the async state machine: a field of a nested type of the
        // page base, annotated for the trimmer, would be reported in every site whose views are kept
        // with all their members (IL2110).
        return ExecuteAndCollectAsync(viewContext, body);
    }

    private async Task<string> ExecuteAndCollectAsync(KazoViewContext viewContext, string? body)
    {
        using StringWriter output = new();
        _writers.Push(output);
        await ExecuteAsync().ConfigureAwait(true);
        if (body is not null && !_bodyRendered && !_bodyIgnored)
        {
            throw new InvalidOperationException($"RenderBody has not been called for the page at '{Path}'. To ignore call IgnoreBody().");
        }

        // Sections become HTML now, written by this page's own code (ASP.NET renders them when the layout asks;
        // the output is the same). A layout may define again a section it rendered, for the layout around it.
        foreach (KeyValuePair<string, Func<Task>> section in _sections)
        {
            using StringWriter sectionOutput = new();
            _writers.Push(sectionOutput);
            await section.Value().ConfigureAwait(true);
            _writers.Pop();
            viewContext.DefineSection(section.Key, sectionOutput.ToString(), replaceRendered: body is not null);
        }

        _writers.Pop();
        return output.ToString();
    }

    /// <summary>
    /// Sets the <c>@inject</c> properties (ASP.NET's <c>RazorPageActivator</c>): a helper of the page, or a
    /// service of the request scope (the same instances as the controller's).
    /// </summary>
    private void Activate([DynamicallyAccessedMembers(KazoViewTypes.Component)] Type pageType, IServiceProvider services)
    {
        foreach (PropertyInfo property in pageType.GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (!property.CustomAttributes.Any(attribute => attribute.AttributeType.FullName == RazorInjectAttributeName))
            {
                continue;
            }

            object value = CreateHelper(property.PropertyType)
                ?? services.GetService(property.PropertyType)
                ?? throw new InvalidOperationException(
                    $"No service for type '{property.PropertyType.FullName}' has been registered (@inject {property.Name} in '{Path}').");
            property.SetValue(this, value);
        }
    }

    private void EnsureLayout(string method)
    {
        if (_body is null)
        {
            throw new InvalidOperationException($"{method} invocation in '{Path}' is invalid. {method} can only be called from a layout page.");
        }
    }

    private sealed class AttributeState(string name, string prefix, string suffix, int valueCount)
    {
        public string Name { get; } = name;

        public string Prefix { get; } = prefix;

        public string Suffix { get; } = suffix;

        public int ValueCount { get; } = valueCount;

        public bool Suppressed { get; set; }
    }
}

/// <summary>
/// A <c>.cshtml</c> page with a typed model: <c>@model Note</c> makes the compiler derive the page from
/// <c>KazoRazorPage&lt;Note&gt;</c> (the root <c>_ViewImports.cshtml</c> says <c>@inherits KazoRazorPage&lt;TModel&gt;</c>).
/// Without <c>@model</c>, <typeparamref name="TModel"/> is <c>dynamic</c>, as in ASP.NET.
/// </summary>
/// <typeparam name="TModel">The model type; the engine refuses another type with a clear error.</typeparam>
public abstract class KazoRazorPage<TModel> : KazoRazorPage
{
    /// <summary>Gets the model the action passed (<c>View(model)</c>), or that a partial received.</summary>
    public TModel Model { get; private set; } = default!;

    /// <inheritdoc />
    private protected override void SetModel(object? model) => Model = model is null ? default! : (TModel)model;

    /// <inheritdoc />
    private protected override object? CreateHelper(Type type) =>
        type == typeof(KazoHtmlHelper<TModel>) ? new KazoHtmlHelper<TModel>(this)
        : type == typeof(KazoModelExpressionProvider<TModel>) ? new KazoModelExpressionProvider<TModel>()
        : base.CreateHelper(type);
}
