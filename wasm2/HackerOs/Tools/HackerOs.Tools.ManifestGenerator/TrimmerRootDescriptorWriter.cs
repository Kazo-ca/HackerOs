using System.Text;
using System.Xml;
using HackerOs.App.Abstractions;

namespace HackerOs.Tools.ManifestGenerator;

/// <summary>
/// Writes the ILLink root descriptor of a host (ADR 0106 §2, ADR 0113) from the manifests it
/// aggregates, so a trimmed publish keeps every app assembly the OS only reaches by name.
/// </summary>
/// <remarks>
/// <para>
/// The OS never references an app's types in code: it lazy-loads the app's assembly and finds its
/// entry point, its embeddable components (ADR 0063) and a site's Blazor root (ADR 0084) by the names
/// the manifest gives (<c>Assembly.GetType</c>, then <c>Activator.CreateInstance</c>). Without a
/// root, the trimmer sees no use of these assemblies and removes them whole.
/// </para>
/// <para>
/// ADR 0113: every assembly a manifest names is kept whole (<c>preserve="all"</c>), not only the
/// named types. App code hands its own records to JavaScript interop and to reflection-based JSON
/// (<c>IJSRuntime.InvokeAsync(..., params object[])</c> is not annotated for the trimmer), so a
/// member-level trim of an app removes properties and constructor parameter names that only
/// serialization reads, with no warning. Measured on the Ecosystem host, member-level trimming of
/// the KazoOS assemblies saved under 1 MB of the 27 MB the framework trimming saves.
/// </para>
/// </remarks>
public static class TrimmerRootDescriptorWriter
{
    /// <summary>Builds the descriptor for <paramref name="manifests"/>.</summary>
    /// <param name="manifests">The host's validated manifests.</param>
    /// <returns>The descriptor XML, stable for the same input (assemblies sorted by name).</returns>
    public static string Build(IEnumerable<AppManifest> manifests)
    {
        ArgumentNullException.ThrowIfNull(manifests);

        SortedSet<string> assemblies = new(StringComparer.Ordinal);
        foreach (AppManifest manifest in manifests)
        {
            if (manifest.EntryPoint is { } entryPoint)
            {
                assemblies.Add(AssemblyName(entryPoint.Assembly));
            }

            foreach (AppPlatformEntryPointManifest platformEntryPoint in manifest.Platform?.EntryPoints ?? [])
            {
                assemblies.Add(AssemblyName(platformEntryPoint.Assembly));
            }

            foreach (AppComponentManifest component in manifest.Components ?? [])
            {
                assemblies.Add(AssemblyName(component.Assembly));
            }

            if (manifest.Web?.Blazor is { } blazor)
            {
                assemblies.Add(AssemblyName(blazor.Assembly));
            }
        }

        StringBuilder text = new();
        using (XmlWriter xml = XmlWriter.Create(text, new XmlWriterSettings
        {
            Indent = true,
            OmitXmlDeclaration = true,
            NewLineChars = "\n",
        }))
        {
            xml.WriteStartElement("linker");
            xml.WriteComment(
                " Generated by the KazoOS manifest generator (ADR 0106, ADR 0113) from BuiltInApplications.json. Do not edit. ");
            foreach (string assembly in assemblies)
            {
                xml.WriteStartElement("assembly");
                xml.WriteAttributeString("fullname", assembly);
                xml.WriteAttributeString("preserve", "all");
                xml.WriteEndElement();
            }

            xml.WriteEndElement();
        }

        return text.Append('\n').ToString();
    }

    /// <summary><c>HackerOs.Apps.Calculator.dll</c> → <c>HackerOs.Apps.Calculator</c>.</summary>
    private static string AssemblyName(string assemblyFile) =>
        assemblyFile.EndsWith(".dll", StringComparison.OrdinalIgnoreCase) ? assemblyFile[..^4] : assemblyFile;
}
